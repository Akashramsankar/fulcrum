// Pre-builds the daily puzzle bank (js/puzzles.js) so the browser never waits on
// the generator. Every board is deterministic, so the bank is a cache: the game
// builds any date outside it with the same code and gets the same board.
//
// Each board is checked independently before it's written (spec §16 I): a fresh
// solver re-proves par, and the solver's line is replayed through the in-game
// rules (word checks, rack, torque) to confirm it balances the beam.
//
// Usage: node scripts/generate.mjs [days=400] [from=EPOCH]
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
globalThis.self = globalThis;
require(join(root, 'js', 'words.js'));
const E = require(join(root, 'js', 'engine.js'));
E.loadDictionary(self.FULCRUM_WORDS.split(' '), self.FULCRUM_COMMON.split(' '));

export const EPOCH = '2026-11-24';
const days = Number(process.argv[2] || 400);
const from = process.argv[3] || EPOCH;
const out = process.env.FULCRUM_OUT || join(root, 'js', 'puzzles.js'); // workers can write to their own file, then merge

const addDays = (key, n) => {
  const [y, m, d] = key.split('-').map(Number);
  return new Date(Date.UTC(y, m - 1, d + n)).toISOString().slice(0, 10);
};

/** Independent check of a built board. Throws on any failure. */
export function validate(p) {
  const fresh = E.makeSolver(p.rack);
  if (E.isBalanced(p.start)) throw new Error('starts balanced');
  if (E.anchorNet(p.anchors) !== p.start) throw new Error('anchors do not match start torque');
  if (fresh.minMoves(p.start, p.par) !== p.par) throw new Error('par not proven');
  const placed = [];
  for (const m of p.line) {
    const why = E.checkWord(m.word, E.rackAfter(p, placed), placed, p.maxMoves - placed.length);
    if (why) throw new Error(`line rejected: ${why}`);
    placed.push({ word: m.word, side: m.side });
  }
  if (placed.length !== p.par || !E.isBalanced(E.netOf(p, placed))) throw new Error('line does not balance at par');
}

// Keep earlier boards that are still valid for this rule set, so a re-run only extends the bank.
let bank = { v: E.fingerprint(), days: {} };
if (existsSync(out)) {
  try {
    const prev = JSON.parse(readFileSync(out, 'utf8').replace(/^[^{]*/, '').replace(/;\s*$/, ''));
    if (prev.v === bank.v) bank = prev;
  } catch (e) { /* rebuild */ }
}

const t0 = Date.now();
for (let i = 0; i < days; i++) {
  const key = addDays(from, i);
  if (bank.days[key]) continue;
  const t = Date.now();
  const built = E.buildDaily(key);
  const solver = E.makeSolver(built.rack);
  const easy = E.makeSolver(built.rack, { pool: 'common' });
  const line = (isFinite(easy.minMoves(built.start, built.par)) && easy.line(built.start, built.par)) || solver.line(built.start, built.par) || built.intended;
  const p = {
    difficulty: built.difficulty, salt: built.salt, rack: built.rack, anchors: built.anchors,
    start: built.start, par: built.par, maxMoves: built.maxMoves,
    line: line.map(({ word, side }) => ({ word, side })),
    quality: built.quality,
  };
  validate(p);
  bank.days[key] = p;
  console.log(`${key} ${p.difficulty.padEnd(6)} par ${p.par} salt ${String(p.salt).padStart(4)} ${p.rack} start ${String(p.start).padStart(4)}  ${Date.now() - t}ms`);
  // write as we go so an interrupted run keeps its progress
  if (i % 10 === 9) save();
}
save();
console.log(`${Object.keys(bank.days).length} boards in bank · ${((Date.now() - t0) / 1000).toFixed(1)}s`);

function save() {
  const sorted = Object.fromEntries(Object.entries(bank.days).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(out, '// Generated by scripts/generate.mjs — do not edit by hand.\nself.FULCRUM_BANK = ' +
    JSON.stringify({ v: bank.v, days: sorted }) + ';\n');
}
