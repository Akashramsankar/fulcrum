// Builds js/words.js from the raw word lists in data/.
//   data/enable1.txt — ENABLE word list (public domain): every word a player may place,
//                      and the list the solver uses to verify par. No proper nouns,
//                      abbreviations, hyphens or apostrophes.
//   data/common.txt  — ~10k everyday English words: the generator builds its intended
//                      solutions from these, and hints prefer them.
// Both lists are versioned together by DICT_VERSION in js/engine.js.
// Usage: node scripts/build-words.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => readFileSync(join(root, 'data', f), 'utf8').split(/\s+/).filter(Boolean);

const MIN = 3;
const MAX = 5; // rule: words are 3–5 letters (see README, "Why words are capped at 5")

const valid = [...new Set(read('enable1.txt').map((w) => w.toUpperCase()))]
  .filter((w) => /^[A-Z]+$/.test(w) && w.length >= MIN && w.length <= MAX)
  .sort();
const validSet = new Set(valid);
const common = [...new Set(read('common.txt').map((w) => w.toUpperCase()))]
  .filter((w) => /^[A-Z]+$/.test(w) && w.length >= MIN && validSet.has(w))
  .sort();

const out =
  '// Generated by scripts/build-words.mjs — do not edit by hand.\n' +
  `self.FULCRUM_WORDS = "${valid.join(' ')}";\n` +
  `self.FULCRUM_COMMON = "${common.join(' ')}";\n`;
writeFileSync(join(root, 'js', 'words.js'), out);
console.log(`words.js: ${valid.length} valid words, ${common.length} common words, ${(out.length / 1024).toFixed(0)} KB`);
